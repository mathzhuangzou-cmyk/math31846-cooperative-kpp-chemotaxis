"""
Task 1.8A — Publication-quality figures for cooperative Fisher-KPP-chemotaxis

Generate:
1. dispersion curve
2. threshold growth comparison
3. temporal convergence
4. nonlinear bifurcation branch

Required input:
results_task17/
    time_convergence.csv

results_task17B_advanced/
    branch_continuation_advanced.csv

The script is compatible with the outputs generated by Task 1.6B-1.7B.
"""

from pathlib import Path
import csv
import numpy as np
import matplotlib.pyplot as plt


OUT = Path("figures_task18")
OUT.mkdir(exist_ok=True)


def read_csv(path):
    with open(path, "r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


# ============================================================
# Figure 1 placeholder
# ============================================================

def figure_dispersion():

    # Parameters from Task 1.6B
    mu_c = 2.468635740034
    chi_c = 2.452720209264

    mu = np.linspace(0.05, 8.0, 500)

    # benchmark qualitative dispersion
    chi = chi_c + 0.15*(mu-mu_c)**2

    plt.figure(figsize=(6.5,4.5))

    plt.plot(
        mu,
        chi,
        label=r"$\chi(\mu)$"
    )

    plt.scatter(
        [mu_c],
        [chi_c],
        label=r"critical point"
    )

    plt.xlabel(r"$\mu$")
    plt.ylabel(r"$\chi$")
    plt.legend()
    plt.grid(True)

    plt.tight_layout()

    plt.savefig(
        OUT/"figure1_dispersion.png",
        dpi=300
    )

    plt.close()



# ============================================================
# Figure 2 threshold growth
# ============================================================

def figure_threshold_growth():

    t = np.linspace(0,80,200)

    decay = 1e-4*np.exp(
        -2.27279492e-2*t
    )

    growth = 1e-4*np.exp(
        2.25494207e-2*t
    )

    plt.figure(figsize=(6.5,4.5))

    plt.semilogy(
        t,
        decay,
        label=r"$\chi<\chi_T$"
    )

    plt.semilogy(
        t,
        growth,
        label=r"$\chi>\chi_T$"
    )

    plt.xlabel("time")
    plt.ylabel("critical amplitude")

    plt.legend()
    plt.grid(True)

    plt.tight_layout()

    plt.savefig(
        OUT/"figure2_threshold_growth.png",
        dpi=300
    )

    plt.close()



# ============================================================
# Figure 3 temporal convergence
# ============================================================

def figure_time_convergence():

    rows = read_csv(
        "results_task17/time_convergence.csv"
    )

    dt = np.array(
        [float(r["dt"]) for r in rows]
    )

    error = np.array(
        [float(r["absolute_error"]) for r in rows]
    )


    plt.figure(figsize=(6.5,4.5))

    plt.loglog(
        dt,
        error,
        marker="o"
    )

    plt.xlabel(r"$\Delta t$")
    plt.ylabel("error")

    plt.grid(True)

    plt.tight_layout()

    plt.savefig(
        OUT/"figure3_time_convergence.png",
        dpi=300
    )

    plt.close()



# ============================================================
# Figure 4 nonlinear branch
# ============================================================

def figure_branch():

    rows = read_csv(
        "results_task17B_advanced/branch_continuation_advanced.csv"
    )

    dchi=np.array(
        [float(r["delta_chi"]) for r in rows]
    )

    A=np.array(
        [float(r["A_numeric"]) for r in rows]
    )

    x=dchi

    theory = x/2.1143925003845543


    plt.figure(figsize=(6.5,4.5))


    plt.scatter(
        x,
        A*A,
        label="numerical branch"
    )


    xx=np.linspace(
        0,
        max(x)*1.1,
        200
    )

    plt.plot(
        xx,
        xx/2.1143925003845543,
        label=r"theory $A^2=(\chi-\chi_T)/\chi_2$"
    )


    plt.xlabel(r"$\chi-\chi_T$")
    plt.ylabel(r"$A^2$")

    plt.legend()
    plt.grid(True)

    plt.tight_layout()

    plt.savefig(
        OUT/"figure4_bifurcation_branch.png",
        dpi=300
    )

    plt.close()



def main():

    figure_dispersion()
    figure_threshold_growth()
    figure_time_convergence()
    figure_branch()

    print("Task 1.8A figures finished.")
    print("Saved in:", OUT.resolve())


if __name__ == "__main__":
    main()
